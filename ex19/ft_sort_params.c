#include <unistd.h>

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

void	ft_putstr(char *str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		ft_putchar(str[i]);
		i++;
	}
}

int	ft_strcmp(char *s1, char *s2)
{
	int	i;

	i = 0;
	while (s1[i] == s2[i] && s1[i] && s2[i])
		i++;
	return (s1[i] - s2[i]);
}

void	ft_sort_params(int argc, char **argv)
{
	int		i;
	int		j;
	int		ind_min;
	char	*tmp;

	i = 1;
	while (i < argc - 1)
	{
		ind_min = i;
		j = i + 1;
		while (j < argc)
		{
			if (ft_strcmp(argv[j], argv[ind_min]) < 0)
				ind_min = j;
			j++;
		}
		tmp = argv[ind_min];
		argv[ind_min] = argv[i];
		argv[i] = tmp;
		i++;
	}
}

int	main(int argc, char **argv)
{
	int	i;

	ft_sort_params(argc, argv);
	i = 1;
	while (i < argc)
	{
		ft_putstr(argv[i]);
		ft_putchar('\n');
		i++;
	}
	return (0);
}
